CREATE TABLE IF NOT EXISTS `{{prefix}}shop_categories` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 slug VARCHAR(120) NOT NULL UNIQUE,
 description TEXT NOT NULL,
 active TINYINT NOT NULL DEFAULT 1,
 revision INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}products` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 slug VARCHAR(120) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL,
 draft_json MEDIUMTEXT NOT NULL,
 published_json MEDIUMTEXT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}product_variants` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 sku VARCHAR(64) NOT NULL UNIQUE,
 size_label VARCHAR(40) NOT NULL,
 color_label VARCHAR(60) NOT NULL,
 price_cents INT UNSIGNED NOT NULL,
 stock INT UNSIGNED NOT NULL DEFAULT 0,
 active TINYINT NOT NULL DEFAULT 1,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 INDEX variant_product (product_id,active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}inventory_adjustments` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 variant_id BIGINT UNSIGNED NOT NULL,
 operation_hash CHAR(64) NOT NULL UNIQUE,
 quantity_delta INT NOT NULL,
 stock_after INT UNSIGNED NOT NULL,
 reason VARCHAR(300) NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL,
 INDEX inventory_variant (variant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}carts` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}cart_items` (
 cart_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 PRIMARY KEY (cart_id,variant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}cart_operations` (
 cart_id BIGINT UNSIGNED NOT NULL,
 nonce_hash CHAR(64) NOT NULL,
 payload_hash CHAR(64) NOT NULL,
 PRIMARY KEY (cart_id,nonce_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}customers` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 session_version INT UNSIGNED NOT NULL DEFAULT 1,
 consent_version VARCHAR(50) NOT NULL,
 created_at DATETIME NOT NULL,
 verified_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}customer_tokens` (
 customer_id BIGINT UNSIGNED NOT NULL,
 purpose VARCHAR(12) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL,
 requested_at DATETIME NOT NULL,
 used_at DATETIME NULL,
 PRIMARY KEY (customer_id,purpose)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}customer_addresses` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 customer_id BIGINT UNSIGNED NOT NULL,
 label VARCHAR(60) NOT NULL,
 recipient VARCHAR(120) NOT NULL,
 line_one VARCHAR(180) NOT NULL,
 line_two VARCHAR(180) NOT NULL,
 city VARCHAR(100) NOT NULL,
 region VARCHAR(100) NOT NULL,
 postal_code VARCHAR(20) NOT NULL,
 country_code CHAR(2) NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 INDEX address_customer (customer_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

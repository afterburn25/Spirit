#!/usr/bin/env node
/**
 * Rebuild the committed public bundles on a development machine or in CI:
 *   npm ci --prefix app/tools/public-assets
 *   node app/tools/build_public_assets.mjs [--check]
 *
 * The hosting package serves these files directly and needs neither Node nor npm.
 * Edit site-source.css and the named JavaScript modules, then run this builder.
 * Historical stylesheet/menu patch paths remain inert for cumulative updates.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(new URL('./public-assets/package.json', import.meta.url));
const { minify: minifyCss } = require('csso');
const { minify: minifyJs } = require('terser');
const arguments_ = process.argv.slice(2);
if (arguments_.some(argument => argument !== '--check')) {
  throw new Error('Usage: node app/tools/build_public_assets.mjs [--check]');
}
const check = arguments_.includes('--check');
const read = relative => readFile(path.join(root, relative), 'utf8');
const cssSource = 'assets/css/site-source.css';
const jsSources = [
  'assets/js/public.js',
  'assets/js/commerce.js',
  'assets/js/quality.js',
  'assets/js/branding.js',
  'assets/js/header-search.js',
];

// Keep URLs in the CSS directory so owner media and bundled artwork resolve
// exactly as before. CSSO preserves conditional rules and browser fallbacks.
const css = minifyCss(await read(cssSource), { restructure: true, comments: false }).css;
const js = await minifyJs(Object.fromEntries(await Promise.all(
  jsSources.map(async relative => [relative, await read(relative)])
)), {
  ecma: 2020,
  compress: { passes: 2 },
  mangle: true,
  format: { comments: false },
});
if (!js.code) throw new Error('The public JavaScript bundle is empty.');
const outputs = new Map([
  ['assets/css/site.css', `/* Generated from site-source.css by tools/build_public_assets.mjs. */\n${css}\n`],
  ['assets/js/site.js', `/* Generated by tools/build_public_assets.mjs; edit the source modules. */\n${js.code}\n`],
]);

// Measure every asset actually referenced by the public shell, including the
// early JS capability marker and optional first-party analytics collector.
// The browser gate separately checks transferred assets for every viewport.
const header = await read('app/views/public/header.php');
const assets = new Set(Array.from(header.matchAll(/assets\/(?:css|js)\/[\w.-]+\.(?:css|js)/g), match => match[0]));
let bytes = 0;
for (const relative of assets) {
  bytes += Buffer.byteLength(outputs.get(relative) ?? await read(relative));
}
if (bytes > 130_000) {
  throw new Error(`Public CSS/JS budget exceeded: ${bytes.toLocaleString('en-US')} / 130,000 bytes.`);
}

let stale = false;
for (const [relative, content] of outputs) {
  if (check) {
    const existing = await read(relative).catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (existing !== content) {
      process.stderr.write(`${relative} is stale; run node app/tools/build_public_assets.mjs.\n`);
      stale = true;
    }
  } else {
    await writeFile(path.join(root, relative), content);
  }
  process.stdout.write(`${relative}: ${Buffer.byteLength(content).toLocaleString('en-US')} bytes\n`);
}
process.stdout.write(`Loaded public CSS/JS: ${bytes.toLocaleString('en-US')} / 130,000 bytes (${assets.size} files).\n`);
if (stale) process.exitCode = 1;

CREATE TABLE IF NOT EXISTS `{{prefix}}orders` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 reference VARCHAR(20) NOT NULL UNIQUE,
 submission_hash CHAR(64) NOT NULL UNIQUE,
 payload_hash CHAR(64) NOT NULL,
 cart_id BIGINT UNSIGNED NOT NULL,
 customer_id BIGINT UNSIGNED NULL,
 buyer_email VARCHAR(190) NOT NULL,
 private_data MEDIUMTEXT NOT NULL,
 environment VARCHAR(12) NOT NULL,
 merchant_login VARCHAR(64) NOT NULL,
 subtotal_cents INT UNSIGNED NOT NULL,
 shipping_cents INT UNSIGNED NOT NULL,
 tax_cents INT UNSIGNED NOT NULL,
 total_cents INT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 payment_state VARCHAR(24) NOT NULL DEFAULT 'awaiting_payment',
 fulfillment_state VARCHAR(24) NOT NULL DEFAULT 'unfulfilled',
 reservation_state VARCHAR(16) NOT NULL DEFAULT 'held',
 expires_at DATETIME NOT NULL,
 access_hash CHAR(64) NOT NULL UNIQUE,
 access_expires_at DATETIME NOT NULL,
 transaction_id VARCHAR(32) NULL,
 last_four CHAR(4) NULL,
 receipt_queued TINYINT NOT NULL DEFAULT 0,
 tracking_carrier VARCHAR(80) NOT NULL DEFAULT '',
 tracking_number VARCHAR(180) NOT NULL DEFAULT '',
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL,
 UNIQUE KEY order_transaction (environment,transaction_id),
 INDEX order_cart (cart_id,payment_state),
 INDEX order_customer (customer_id,id),
 INDEX order_expiry (payment_state,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}order_items` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(160) NOT NULL,
 sku VARCHAR(64) NOT NULL,
 variant_label VARCHAR(120) NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_cents INT UNSIGNED NOT NULL,
 line_cents INT UNSIGNED NOT NULL,
 UNIQUE KEY order_variant (order_id,variant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}payment_operations` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 kind VARCHAR(12) NOT NULL,
 reference VARCHAR(20) NOT NULL UNIQUE,
 nonce_hash CHAR(64) NOT NULL,
 amount_cents INT UNSIGNED NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'processing',
 transaction_id VARCHAR(32) NULL,
 last_error VARCHAR(80) NULL,
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL,
 UNIQUE KEY order_operation (order_id,kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}order_events` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 event VARCHAR(60) NOT NULL,
 actor_id BIGINT UNSIGNED NULL,
 detail VARCHAR(300) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL,
 INDEX order_timeline (order_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `{{prefix}}payment_webhooks` (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 environment VARCHAR(12) NOT NULL,
 notification_id VARCHAR(80) NOT NULL,
 transaction_id VARCHAR(32) NOT NULL,
 event_type VARCHAR(100) NOT NULL,
 merchant_reference VARCHAR(20) NOT NULL DEFAULT '',
 body_hash CHAR(64) NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'queued',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 available_at DATETIME NOT NULL,
 last_error VARCHAR(80) NULL,
 created_at DATETIME NOT NULL,
 completed_at DATETIME NULL,
 UNIQUE KEY webhook_notification (environment,notification_id),
 INDEX webhook_work (state,available_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
